CREATE OR REPLACE FUNCTION public.registrar_promocion_mixta(
    p_items jsonb,
    p_tipo text,
    p_precio_promocional numeric DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_rol text;
    v_folio uuid := gen_random_uuid();
    v_item jsonb;
    v_id text;
    v_cantidad integer;
    v_nombre text;
    v_precio numeric(12,2);
    v_stock numeric;
    v_total_unidades integer := 0;
    v_suma_regular numeric(12,2) := 0;
    v_unidades_grupo integer;
    v_unidades_gratis integer := 0;
    v_descuento numeric(12,2) := 0;
    v_importe numeric(12,2) := 0;
    v_precios numeric[] := ARRAY[]::numeric[];
    v_producto record;
BEGIN
    SELECT UPPER(rol) INTO v_rol
      FROM public.profiles
     WHERE id = auth.uid() AND COALESCE(activo, true) = true
     LIMIT 1;
    IF auth.uid() IS NULL OR v_rol IS NULL OR v_rol NOT IN ('MASTER','ADMIN','VENTAS') THEN
        RAISE EXCEPTION 'Acción permitida únicamente para perfiles MASTER, ADMIN o VENTAS activos.' USING ERRCODE = '42501';
    END IF;
    IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Selecciona al menos un producto.';
    END IF;

    -- Rechazar IDs repetidos para que la validación de stock no cuente líneas duplicadas.
    IF EXISTS (
        SELECT 1
          FROM jsonb_array_elements(p_items) AS x(value)
         GROUP BY x.value->>'producto_id'
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'La promoción contiene productos repetidos. Consolida sus cantidades en una sola línea.';
    END IF;

    -- Bloquear productos siempre por ID ascendente para reducir interbloqueos.
    FOR v_item IN
        SELECT value FROM jsonb_array_elements(p_items) AS x(value)
         ORDER BY value->>'producto_id'
    LOOP
        v_id := v_item->>'producto_id';
        v_cantidad := (v_item->>'cantidad')::integer;
        IF v_id IS NULL OR v_cantidad IS NULL OR v_cantidad < 1 THEN
            RAISE EXCEPTION 'Cada producto requiere un ID y una cantidad entera positiva.';
        END IF;
        SELECT nombre, precio, stock INTO v_nombre, v_precio, v_stock
          FROM public.productos WHERE id::text = v_id FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró el producto %.', v_id; END IF;
        IF v_stock < v_cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para %. Disponible: %, requerido: %.', v_nombre, v_stock, v_cantidad;
        END IF;
        v_total_unidades := v_total_unidades + v_cantidad;
        v_suma_regular := v_suma_regular + (v_precio * v_cantidad);
        v_precios := v_precios || array_fill(v_precio, ARRAY[v_cantidad]);
    END LOOP;

    CASE p_tipo
      WHEN '4x3' THEN
        v_unidades_grupo := 4;
        IF v_total_unidades % 4 <> 0 THEN RAISE EXCEPTION 'La promoción 4x3 requiere cantidades totales múltiplos de 4.'; END IF;
      WHEN '3x2' THEN
        v_unidades_grupo := 3;
        IF v_total_unidades % 3 <> 0 THEN RAISE EXCEPTION 'La promoción 3x2 requiere cantidades totales múltiplos de 3.'; END IF;
      WHEN '2x1' THEN
        v_unidades_grupo := 2;
        IF v_total_unidades % 2 <> 0 THEN RAISE EXCEPTION 'La promoción 2x1 requiere cantidades totales múltiplos de 2.'; END IF;
      WHEN 'PRECIO_PROMO' THEN
        v_unidades_grupo := 1;
        IF p_precio_promocional IS NULL OR p_precio_promocional < 0 THEN RAISE EXCEPTION 'Indica un precio promocional total válido.'; END IF;
      ELSE RAISE EXCEPTION 'Tipo de promoción no válido.';
    END CASE;

    IF p_tipo = 'PRECIO_PROMO' THEN
        v_importe := ROUND(p_precio_promocional, 2);
    ELSE
        v_unidades_gratis := (v_total_unidades / v_unidades_grupo) * CASE p_tipo WHEN '4x3' THEN 1 WHEN '3x2' THEN 1 WHEN '2x1' THEN 1 ELSE 0 END;
        SELECT COALESCE(SUM(precio),0) INTO v_descuento
          FROM (SELECT unnest(v_precios) AS precio ORDER BY precio LIMIT v_unidades_gratis) AS gratis;
        v_importe := GREATEST(0, ROUND(v_suma_regular - v_descuento, 2));
    END IF;

    -- Descontar y guardar una línea por producto. El folio agrupa todas las líneas;
    -- el importe total se repite para consulta, y la UI lo cuenta una sola vez por folio.
    FOR v_item IN
        SELECT value FROM jsonb_array_elements(p_items) AS x(value)
         ORDER BY value->>'producto_id'
    LOOP
        v_id := v_item->>'producto_id';
        v_cantidad := (v_item->>'cantidad')::integer;
        SELECT nombre INTO v_nombre FROM public.productos WHERE id::text = v_id;
        UPDATE public.productos SET stock = stock - v_cantidad WHERE id::text = v_id;
        INSERT INTO public.promociones
          (folio_promocion, producto_id, producto_nombre, tipo, unidades, importe_cobrado, usuario_id, usuario_rol)
        VALUES
          (v_folio, v_id, v_nombre, p_tipo, v_cantidad, v_importe, auth.uid(), v_rol);
    END LOOP;

    RETURN jsonb_build_object('folio_promocion',v_folio,'unidades',v_total_unidades,
      'importe_promocional',v_importe,'stock_descontado',true,
      'venta_normal_generada',false,'comision_generada',false);
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_promocion_mixta(jsonb, text, numeric) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.registrar_promocion_mixta(jsonb, text, numeric) FROM anon;
GRANT EXECUTE ON FUNCTION public.registrar_promocion_mixta(jsonb, text, numeric) TO authenticated;
