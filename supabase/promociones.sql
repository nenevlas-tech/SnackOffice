-- SnackOffice: módulo de promociones.
-- Ejecutar una sola vez en Supabase SQL Editor antes de usar el módulo.
-- Las promociones descuentan stock y se registran en su propia tabla; no crean ventas ni comisiones.

CREATE TABLE IF NOT EXISTS public.promociones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamptz NOT NULL DEFAULT now(),
    producto_id text NOT NULL,
    producto_nombre text NOT NULL,
    tipo text NOT NULL,
    unidades integer NOT NULL CHECK (unidades > 0),
    importe_cobrado numeric(12,2) NOT NULL DEFAULT 0 CHECK (importe_cobrado >= 0),
    usuario_id uuid,
    usuario_rol text
);

ALTER TABLE public.promociones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.promociones FROM anon;
GRANT SELECT ON TABLE public.promociones TO authenticated;

DROP POLICY IF EXISTS promociones_select_authenticated ON public.promociones;
CREATE POLICY promociones_select_authenticated
ON public.promociones FOR SELECT TO authenticated
USING (true);

CREATE OR REPLACE FUNCTION public.registrar_promocion(
    p_producto_id text,
    p_tipo text,
    p_cantidad integer,
    p_precio_promocional numeric DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_rol text;
    v_nombre text;
    v_precio numeric(12,2);
    v_stock numeric;
    v_unidades integer;
    v_importe numeric(12,2);
    v_paquetes_cobrados integer;
BEGIN
    SELECT UPPER(rol) INTO v_rol
    FROM public.profiles
    WHERE id = auth.uid() AND COALESCE(activo, true) = true
    LIMIT 1;

    IF auth.uid() IS NULL OR v_rol IS NULL OR v_rol NOT IN ('MASTER','ADMIN','VENTAS') THEN
        RAISE EXCEPTION 'Acción permitida únicamente para perfiles MASTER, ADMIN o VENTAS activos.'
            USING ERRCODE = '42501';
    END IF;

    IF p_cantidad IS NULL OR p_cantidad < 1 THEN
        RAISE EXCEPTION 'La cantidad debe ser un entero mayor a cero.';
    END IF;

    SELECT nombre, precio, stock
      INTO v_nombre, v_precio, v_stock
      FROM public.productos
     WHERE id::text = p_producto_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró el producto seleccionado.';
    END IF;

    CASE p_tipo
        WHEN '4x3' THEN
            v_unidades := p_cantidad * 4;
            v_paquetes_cobrados := 3;
            v_importe := ROUND(v_precio * v_paquetes_cobrados * p_cantidad, 2);
        WHEN '3x2' THEN
            v_unidades := p_cantidad * 3;
            v_paquetes_cobrados := 2;
            v_importe := ROUND(v_precio * v_paquetes_cobrados * p_cantidad, 2);
        WHEN '2x1' THEN
            v_unidades := p_cantidad * 2;
            v_paquetes_cobrados := 1;
            v_importe := ROUND(v_precio * v_paquetes_cobrados * p_cantidad, 2);
        WHEN 'PRECIO_PROMO' THEN
            v_unidades := p_cantidad;
            IF p_precio_promocional IS NULL OR p_precio_promocional < 0 THEN
                RAISE EXCEPTION 'Indica un precio promocional válido.';
            END IF;
            v_importe := ROUND(p_precio_promocional, 2);
        ELSE
            RAISE EXCEPTION 'Tipo de promoción no válido.';
    END CASE;

    IF v_stock < v_unidades THEN
        RAISE EXCEPTION 'Existencias insuficientes. Disponibles: %, requeridas: %.', v_stock, v_unidades;
    END IF;

    UPDATE public.productos
       SET stock = stock - v_unidades
     WHERE id::text = p_producto_id;

    INSERT INTO public.promociones
        (producto_id, producto_nombre, tipo, unidades, importe_cobrado, usuario_id, usuario_rol)
    VALUES
        (p_producto_id, v_nombre, p_tipo, v_unidades, v_importe, auth.uid(), v_rol);

    RETURN jsonb_build_object(
        'producto_id', p_producto_id,
        'producto_nombre', v_nombre,
        'tipo', p_tipo,
        'unidades', v_unidades,
        'importe_cobrado', v_importe,
        'stock_restante', v_stock - v_unidades,
        'venta_normal_generada', false,
        'comision_generada', false
    );
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_promocion(text, text, integer, numeric) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.registrar_promocion(text, text, integer, numeric) FROM anon;
GRANT EXECUTE ON FUNCTION public.registrar_promocion(text, text, integer, numeric) TO authenticated;

